// Writes src/server/emoji_qualified.txt, the table qualify_emoji reads,
// from Unicode's emoji-test.txt:
//
//   curl -sSfLO https://unicode.org/Public/emoji/latest/emoji-test.txt
//   node tools/emoji/generate.mjs emoji-test.txt > src/server/emoji_qualified.txt
//
// It keeps each fully-qualified sequence that holds U+FE0F, one per line:
// the ones whose form without U+FE0F a client may send (§4.7).
import { readFileSync } from "node:fs";

const [path] = process.argv.slice(2);
if (!path) throw new Error("usage: node tools/emoji/generate.mjs <emoji-test.txt>");
const text = readFileSync(path, "utf8");
const version = /^# Version: (.+)$/m.exec(text)?.[1];
if (!version) throw new Error("no '# Version:' line: is this emoji-test.txt?");
const bare = new Map();
for (const line of text.split("\n")) {
  const match = /^([0-9A-F ]+?)\s*; fully-qualified\s*#/.exec(line);
  if (!match) continue;
  const sequence = String.fromCodePoint(...match[1].split(" ").map((hex) => parseInt(hex, 16)));
  if (!sequence.includes("️")) continue;
  const key = sequence.replaceAll("️", "");
  if (bare.has(key)) throw new Error(`two sequences differ only in U+FE0F: ${match[1]}`);
  bare.set(key, sequence);
}
process.stdout.write(`// Generated by tools/emoji/generate.mjs from emoji-test.txt ${version}.\n`);
for (const sequence of bare.values()) process.stdout.write(`${sequence}\n`);
